/**
 * Generates the derived Synapse Studio data from the studio's own library files:
 *   src/lib/kyp/studio-region-drugs.ts          region id -> drugs acting there (used by /anatomy Brain Mode)
 *   public/synapse-studio/js/data-links.js      which studio drugs have a /drugs/<slug> page
 *   docs/synapse-studio/CLINICAL_REVIEW.md      per-medication checklist for a human reviewer
 * Re-run after public/synapse-studio/js/data-drugs*.js changes:  node scripts/synapse/gen-studio-data.mjs
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const JS = path.join(ROOT, "public", "synapse-studio", "js");
const win = {};
const ctx = vm.createContext({ window: win, console, Math, Object, JSON });
ctx.global = win;
for (const f of ["data-brain.js", "data-drugs.js", "data-drugs-extra.js", "data-drugs-types.js", "data-drugs-more.js"]) {
  vm.runInContext(fs.readFileSync(path.join(JS, f), "utf8"), ctx, { filename: f });
}
const C = win.KYP_CORE, LIB = win.KYP_DRUGS, ACTIONS = win.KYP_ACTIONS;
if (!C || !LIB) throw new Error("studio data did not load");
const drugs = Object.values(LIB).sort((a, b) => a.name.localeCompare(b.name));

// Studio region id -> /anatomy Brain Mode group id (see src/lib/anatomy/brain-registry.ts)
const REGION_GROUP = {
  pfc: "frontal-cortex", motor: "frontal-cortex", parietal: "parietal-cortex", temporal: "temporal-cortex",
  occipital: "occipital-cortex", acc: "limbic-system", amygdala: "limbic-system", hippocampus: "limbic-system",
  bf: "limbic-system", thalamus: "thalamus", hypothalamus: "hypothalamus", striatum: "basal-ganglia",
  nacc: "basal-ganglia", vta: "midbrain", sn: "midbrain", pag: "midbrain", raphe: "brainstem", lc: "brainstem",
  medulla: "brainstem", cerebellum: "cerebellum",
};
for (const id of Object.keys(C.REGIONS)) if (!REGION_GROUP[id]) throw new Error("no anatomy group for region " + id);

// 1) region -> drugs
const byRegion = {};
for (const id of Object.keys(C.REGIONS)) byRegion[id] = [];
for (const d of drugs) for (const r of d.regions) byRegion[r.id].push({ id: d.id, name: d.name, cls: d.class, effect: r.effect });
let ts = "/**\n * Generated by scripts/synapse/gen-studio-data.mjs from the Synapse Studio library. Do not edit by hand.\n * Region id (Synapse Studio) -> medications whose action changes signalling there.\n */\n";
ts += 'export type StudioEffect = "up" | "down" | "mixed";\n';
ts += "export interface StudioRegionDrug { id: string; name: string; cls: string; effect: StudioEffect }\n\n";
ts += "export const STUDIO_REGION_NAMES: Record<string, string> = " + JSON.stringify(Object.fromEntries(Object.entries(C.REGIONS).map(([k, v]) => [k, v.name])), null, 2) + ";\n\n";
ts += "/** Studio region id -> /anatomy Brain Mode group id. */" + String.fromCharCode(10) + "export const STUDIO_REGION_GROUP: Record<string, string> = " + JSON.stringify(REGION_GROUP, null, 2) + ";" + String.fromCharCode(10, 10);
ts += "export const STUDIO_REGION_DRUGS: Record<string, StudioRegionDrug[]> = " + JSON.stringify(byRegion) + ";\n";
fs.writeFileSync(path.join(ROOT, "src", "lib", "kyp", "studio-region-drugs.ts"), ts.replace(/\n/g, "\n"));

// 2) which drugs have a /drugs page
const dir = path.join(ROOT, "src", "lib", "kyp", "data", "drugs");
const pages = new Set();
for (const f of fs.readdirSync(dir)) {
  if (!f.endsWith(".ts") || f === "index.ts") continue;
  const m = fs.readFileSync(path.join(dir, f), "utf8").match(/^\s{2}slug:\s*"([^"]+)"/m);
  if (m) pages.add(m[1]);
}
const withPage = drugs.map((d) => d.id).filter((id) => pages.has(id));
fs.writeFileSync(path.join(JS, "data-links.js"),
  "/* Generated by scripts/synapse/gen-studio-data.mjs: studio medications that have a /drugs/<slug> page. */\n" +
  "window.KYP_STUDIO_LINKS = { drugPages: " + JSON.stringify(withPage) + ", regionGroup: " + JSON.stringify(REGION_GROUP) + " };\n");

// 3) clinical review checklist
let md = "# Synapse Studio: clinical review checklist\n\n" +
  "The mechanisms, regions and plain-language text for the " + drugs.length + " medications in Synapse Studio follow standard pharmacology references but have **not** had a human clinical review.\n" +
  "A qualified reviewer should check each row against current references and record the result. Generated by `scripts/synapse/gen-studio-data.mjs`; keep the Reviewer and Date columns when regenerating.\n\n" +
  "Check for each medication: mechanism archetype and targets, the brain regions and direction of effect, the \"used for\" and onset text, and the simplifications note.\n\n" +
  "| Medication | Class | Mechanism shown | Acts on | Regions | Reviewer | Date | Result |\n|---|---|---|---|---|---|---|---|\n";
for (const d of drugs) {
  md += `| ${d.name} | ${d.class} | ${ACTIONS[d.action] ? ACTIONS[d.action].label : d.action} | ${d.actsOn.join(", ")} | ${d.regions.map((r) => r.id + (r.effect === "up" ? "+" : r.effect === "down" ? "-" : "~")).join(" ")} |  |  |  |\n`;
}
fs.writeFileSync(path.join(ROOT, "docs", "synapse-studio", "CLINICAL_REVIEW.md"), md);
console.log(`drugs=${drugs.length} withPage=${withPage.length} regionCounts=` + Object.entries(byRegion).map(([k, v]) => k + ":" + v.length).join(" "));
