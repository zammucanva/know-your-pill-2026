import { drugs } from "@/lib/kyp/data";
import { getPatientGuide } from "@/lib/kyp/patient";
import { explainPatient } from "@/lib/kyp/modes";
import { gapRows } from "./gap-register";
import { guideFigureSentences } from "./review-readiness";

/**
 * The patient-content safety report: which registry sentences are withheld because they state a dose, a wait or a
 * time-to-effect figure with no source statement, which authored-guide sentences carry such figures, and which
 * Patient parts are still unavailable. Generated from the same functions the page uses.
 */
export function patientSafetyReport(): string {
  const withheld: { slug: string; text: string }[] = [];
  for (const d of drugs) {
    if (getPatientGuide(d.slug)) continue;
    const e = explainPatient(d, undefined);
    for (const s of [...e.plainWords, ...e.summary, ...e.reminders, ...e.sideEffects]) if (s.rule?.id === "unsourced-figure") withheld.push({ slug: d.slug, text: s.text });
  }
  const guides = drugs.filter((d) => getPatientGuide(d.slug)).map((d) => ({ slug: d.slug, figs: guideFigureSentences(getPatientGuide(d.slug)) }));
  const unavailable = gapRows().filter((r) => r.unavailableParts);
  const L: string[] = ["# Patient content safety report", ""];
  L.push("Generated by `bun scripts/evidence/patient-safety-report.ts`; do not edit by hand. Nothing here is clinical review.", "");
  L.push("## Fixed: unsupported time-to-effect, wait and dose figures", "");
  L.push(`${withheld.length} registry sentences for medicines without a Patient Guide state when something happens or how much to take, with no stored source statement. They are no longer shown as guidance; they stay in the "not shown as guidance (needs review)" list on the medicine's page. Source-backed label statements still show their figures, with the source beside them. A safety threshold inside a safety statement (for example a patch strength with a food warning) is not treated as an instruction.`, "");
  for (const w of withheld) L.push(`- ${w.slug}: ${w.text}`);
  L.push("", "## Open: figures in authored Patient Guides", "");
  L.push("Authored guides are not traced sentence by sentence to a source. These sentences state a dose, a wait or a time frame and must be checked by a qualified reviewer against current Indian product information (see `clinical-review-readiness.md`).", "");
  for (const g of guides.filter((x) => x.figs.length)) L.push(`- ${g.slug}: ${g.figs.length} sentence(s)`);
  L.push("", "## Still unavailable (shown as unavailable, never as a reason to avoid the medicine)", "");
  for (const r of unavailable) L.push(`- ${r.name} (${r.slug}): ${r.unavailableParts.split("; ").join(", ")}`);
  L.push("", "## Regression checks", "", "`tests/patient-content-safety.test.ts` (figure detector, nothing shown with such a figure, jurisdiction note on every source-backed card, unavailable-state wording), `tests/source-classification.test.ts`, `tests/safety-alert-part-state.test.ts`, `tests/a11y-explainer.test.ts`, `tests/list-semantics.test.ts`, `tests/readability-edits.test.ts`.", "");
  return L.join("\n");
}
