import { CLAIM_RECORDS } from "./index";
import { getPatientGuide } from "@/lib/kyp/patient";
import { IN_SHORT_PACKET, VIVA_PACKET, packetDigest, reviewItems, vivaFindings } from "./review-packet";
import { packetStatus } from "./review-record";
import { REVIEW_FLAGS, REVIEW_RECORDS } from "@/lib/kyp/modes";
import { UNSOURCED_DOSE, UNSOURCED_TIMING, UNSOURCED_WAIT } from "@/lib/kyp/modes/patient-explanation";

const strings = (v: unknown, out: string[] = []): string[] => {
  if (typeof v === "string") out.push(v);
  else if (Array.isArray(v)) v.forEach((x) => strings(x, out));
  else if (v && typeof v === "object") Object.values(v).forEach((x) => strings(x, out));
  return out;
};
/** Sentences in an authored guide that state a dose, a wait or a time frame: figures a reviewer must check against product information. */
export function guideFigureSentences(guide: unknown): string[] {
  return strings(guide).flatMap((t) => t.split(/(?<=[.!?])\s+/)).filter((x) => UNSOURCED_TIMING.test(x) || UNSOURCED_DOSE.test(x) || UNSOURCED_WAIT.test(x));
}

/**
 * The clinical review readiness report: for each prepared packet, what it holds, what a reviewer must supply, what is
 * unresolved, and the hash identity of the content. Status is "pending" unless a valid record exists; this report
 * never turns a template or a passing structure check into approval.
 */
export const PACKETS = ["sertraline", "fluoxetine", IN_SHORT_PACKET, VIVA_PACKET] as const;

export const REVIEWER_REQUIREMENTS = [
  "A named individual (not software, this application or its tooling), with a professional qualification relevant to the content, the registration body and registration number, an affiliation, a conflicts-of-interest statement and the review date.",
  "A scope statement in the reviewer's own words: what was reviewed and against what (for example the current Indian package insert).",
  "A decision for every item: accept, amend (with the amended wording), reject, request-evidence or unresolved.",
  "A recorded rationale for every decision, including acceptance (what it was checked against).",
  "The record must carry the packet digest and every item's content hash from the template. If any item's wording, passage, source metadata, formulation or applicability changes afterwards, the decision is stale and the item needs review again.",
  "A passing `bun scripts/evidence/review-record-check.ts` means only that the record is complete. It is not clinical approval, and the application does not read records.",
];

export interface PacketReadiness {
  packet: string;
  items: number;
  digest: string;
  status: string;
  detail: string;
  unresolved: string[];
}

export function packetReadiness(): PacketReadiness[] {
  return PACKETS.map((packet) => {
    const items = reviewItems(packet);
    const claims = CLAIM_RECORDS.filter((c) => c.slug === packet);
    const unresolved: string[] = [];
    if (packet === VIVA_PACKET) unresolved.push(...vivaFindings().map((v) => `${v.id}: ${v.reason} (formatting) plus an unsourced figure to confirm`));
    else if (packet === IN_SHORT_PACKET) unresolved.push("Every sentence: say the same as every source wording it stands for, keep any condition, number or limit, and cannot be read as advice for one person.");
    else {
      const guide = getPatientGuide(packet);
      if (guide) {
        const figs = guideFigureSentences(guide);
        if (figs.length) unresolved.push(`${figs.length} guide sentence(s) state a dose, a wait or a time frame (check each figure against current product information): ${figs.slice(0, 3).map((f) => `"${f.slice(0, 70)}"`).join("; ")}${figs.length > 3 ? "; ..." : ""}`);
      }
      if (guide) unresolved.push(`Patient Guide (${items.filter((i) => i.id.startsWith("guide:")).length} groups) is authored text with no claim-level label source: check against current Indian product information.`);
      const open = claims.filter((c) => c.openQuestions.length);
      if (open.length) unresolved.push(`${open.length} source-backed statement(s) carry open questions (for example confirm the brand): ${open.map((c) => c.id).slice(0, 4).join(", ")}${open.length > 4 ? ", ..." : ""}`);
      for (const f of REVIEW_FLAGS.filter((x) => x.slug === packet)) unresolved.push(`Flagged: ${f.path}: ${f.reason}`);
    }
    const st = packetStatus(null, items);
    return { packet, items: items.length, digest: packetDigest(items), status: st.status, detail: st.problems[0], unresolved };
  });
}

export function readinessReport(): string {
  const rows = packetReadiness();
  const L: string[] = ["# Clinical review readiness", ""];
  L.push("Generated by `bun scripts/evidence/review-readiness.ts`; do not edit by hand. It describes preparation. **No packet has a review record, no claim is reviewed, and nothing here is clinical approval.**", "");
  L.push(`- In-app review records (\`REVIEW_RECORDS\`): ${REVIEW_RECORDS.length}`);
  L.push(`- Evidence claims marked reviewed: ${CLAIM_RECORDS.filter((c) => c.review !== "not-reviewed").length} of ${CLAIM_RECORDS.length}`, "");
  L.push("## Packets", "", "| Packet | Items | Status | Packet digest | Packet file | Record template |", "|---|---:|---|---|---|---|");
  for (const r of rows) L.push(`| ${r.packet} | ${r.items} | ${r.status} | \`${r.digest}\` | \`reports/medication-audit/review-packets/${r.packet}.md\` | \`${r.packet}.record-template.json\` |`);
  L.push("", "## Unresolved before any decision", "");
  for (const r of rows) {
    L.push(`### ${r.packet}`, "");
    for (const u of r.unresolved) L.push(`- ${u}`);
    L.push("");
  }
  L.push("## What a reviewer must supply", "");
  for (const x of REVIEWER_REQUIREMENTS) L.push(`- ${x}`);
  L.push("", "## Hash and version integrity", "", "Each item has a content hash over its wording, exact passage, source metadata (title, address, identifier, date, formulation, jurisdiction, type, organisation), applicability and limits; the packet digest covers every item hash. The in-app record format (`REVIEW_RECORDS`) is per fact: one medicine, one path and the hash of the reviewed value, with no wildcard.", "");
  return L.join("\n");
}
