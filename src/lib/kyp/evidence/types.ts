/**
 * Evidence model for patient-facing medication claims.
 *
 * A SOURCE is a document that was actually retrieved: its identity, where it applies (jurisdiction,
 * formulation) and verbatim excerpts captured by a script. A CLAIM is one patient-facing statement, tied to
 * one excerpt of one source, with the exact passage it rests on.
 *
 * What this model does NOT do:
 *   - It does not approve anything. `review` is always "not-reviewed" until a qualified reviewer's record
 *     exists (there is none). Engineering checks only prove that the quoted passage really is in the source.
 *   - It does not say a source applies to every formulation or patient. Each claim carries its own limits.
 *   - It does not make a US label an Indian label. Jurisdiction is explicit on every source and claim.
 *
 * Data (sources, discovery results) is regenerated by scripts/evidence/*. Claims are authored by people or
 * by an assistant, grounded in a stored excerpt, and validated in tests.
 */

export type EvidenceJurisdiction = "IN" | "US" | "UK" | "EU" | "other";

export type SourceType =
  | "indian-regulatory-record" // CDSCO approval / licensing record
  | "indian-product-label" // Indian package insert / prescribing information
  | "indian-safety-communication" // IPC / PvPI alert
  | "indian-institutional" // other Indian government or institutional source
  | "us-product-label" // FDA-approved labelling published on DailyMed
  | "international-patient-information" // e.g. MedlinePlus
  | "international-regulator-label"
  | "clinical-guideline";

export interface SourceExcerpt {
  id: string;
  /** Section heading as it appears in the source (e.g. "INDICATIONS AND USAGE"). */
  section: string;
  /** LOINC section code for SPL labels, when present. */
  loinc?: string;
  /** Verbatim text captured by the script (whitespace normalised, tags removed). */
  text: string;
  /** True if the section was longer than the capture limit and was cut. */
  truncated: boolean;
}

export interface SourceRecord {
  /** Stable id: `<slug>:<type>:<identifier>`. */
  id: string;
  slug: string;
  ingredient: string;
  productTitle: string;
  formulation?: string;
  organisation: string;
  type: SourceType;
  jurisdiction: EvidenceJurisdiction;
  /** Exact document title as published. */
  title: string;
  url: string;
  /** Durable identifier (for DailyMed: the SPL set id). */
  identifier: string;
  publishedDate?: string;
  revision?: number;
  /** ISO date the document was retrieved. */
  accessedAt: string;
  excerpts: SourceExcerpt[];
  /** Where this source does not apply, or what it cannot support. */
  limitations: string[];
}

export type ClaimCategory =
  | "what-it-is"
  | "used-for"
  | "onset"
  | "how-to-take"
  | "precaution"
  | "side-effects"
  | "interactions"
  | "stopping"
  | "urgent-help"
  | "monitoring"
  | "contraindication";

export interface ClaimRecord {
  /** Stable id: `<slug>:<category>:<n>`. */
  id: string;
  slug: string;
  category: ClaimCategory;
  /** The patient-facing wording shown to the reader. */
  patientWording: string;
  /** "exact-quote": wording is the passage itself. "paraphrase": a plain-language restatement of it. */
  wordingKind: "exact-quote" | "paraphrase";
  sourceId: string;
  excerptId: string;
  /** The exact words of the source this claim rests on. Must appear in the stored excerpt. */
  passage: string;
  /** Who/what the claim applies to (formulation, population, jurisdiction). Never empty. */
  applicability: string[];
  /** What a reader or reviewer must not assume from this claim. */
  limitations: string[];
  /** Shared-claim rule this claim is a medicine-specific replacement for, if any (see modes/shared-claims). */
  replacesRule?: string;
  /** Script check only: the passage was found in the stored excerpt. NOT a statement that the claim is correct. */
  verification: "passage-found-in-source" | "unverified";
  /** Always "not-reviewed" in this repository: no qualified review has been recorded. */
  review: "not-reviewed";
  /** Open questions for the reviewer. */
  openQuestions: string[];
}

export interface DiscoveryCandidate {
  title: string;
  setid: string;
  publishedDate: string;
  version: number;
}
export interface DiscoveryRecord {
  slug: string;
  queryUsed: string;
  status: "candidates-found" | "none-found" | "error";
  candidates: DiscoveryCandidate[];
  totalFound: number;
  accessedAt: string;
  note?: string;
}

export interface EvidenceClaimView {
  claim: ClaimRecord;
  source: Pick<SourceRecord, "title" | "url" | "identifier" | "publishedDate" | "accessedAt" | "organisation" | "jurisdiction" | "formulation" | "type">;
}

/** One question-headed section of a US Medication Guide, captured verbatim by scripts/evidence/medguide.ts. */
export interface MedGuideSection {
  heading: string;
  text: string;
  truncated: boolean;
}
export interface MedGuideRecord {
  slug: string;
  status: "medication-guide-found" | "no-medication-guide-in-labels-checked" | "no-us-label-found" | "error";
  labelTitle?: string;
  setid?: string;
  publishedDate?: string;
  version?: number;
  accessedAt: string;
  labelsChecked: number;
  sections: MedGuideSection[];
  note?: string;
}
